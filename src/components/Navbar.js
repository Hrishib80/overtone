export function createNavbar(currentPath, badges = {}) {
  const nav = createElement('nav', { className: 'bottom-nav' });
  
  const items = [
    { path: '/', icon: icons.discover, label: 'Discover', id: 'discover' },
    { path: '/matches', icon: icons.matches, label: 'Matches', id: 'matches' },
    { path: '/chat', icon: icons.chat, label: 'Chat', id: 'chat' },
    { path: '/profile', icon: icons.profile, label: 'Profile', id: 'profile' }
  ];
  
  items.forEach(item => {
    const a = createElement('a', {
      className: `bottom-nav__item ${currentPath === item.path ? 'active' : ''}`,
      href: item.path
    });
    // Set data-link for SPA router
    a.setAttribute('data-link', '');
    
    a.innerHTML = item.icon;
    
    const label = createElement('span', { className: 'bottom-nav__label' }, item.label);
    a.appendChild(label);
    
    if (badges[item.id] > 0) {
      const badge = createElement('span', { className: 'badge new' }, badges[item.id].toString());
      a.appendChild(badge);
    }
    
    nav.appendChild(a);
  });
  
  return nav;
}
